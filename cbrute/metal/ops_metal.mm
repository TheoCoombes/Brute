// brute Metal/MPS backend — driver layer.
//
// Mirrors the CPU + CUDA backend split:
//   * Kernels live in cbrute/metal/kernels/*.metal (one .metal file per
//     domain), compiled AOT by CMake into a single .metallib whose bytes are
//     embedded into the extension via brute_kernels_data.h (a generated
//     header).
//   * This .mm file is the host-side driver: shape validation, output
//     allocation, dispatch-helper plumbing, and PipelineCache.
//
// Why AOT? Apple's runtime MSL compiler is slow (~tens of ms for the legacy
// inlined string) and only validates kernels on first use. AOT shifts both
// costs to build time and lets us ship a single .so. We load the embedded
// bytes via [device newLibraryWithData:] at startup.
//
// Stream integration: when PyTorch's MPS stream is available we encode into
// its current command buffer. Before opening any compute encoder we MUST call
// `stream->endKernelCoalescing()` — otherwise a prior at:: op (e.g.
// at::bitwise_xor in a composite fallback) may still hold an encoder open on
// the same command buffer, triggering Metal's "A command encoder is already
// encoding to this command buffer" abort.

#ifdef HAVE_MPS
#import <Metal/Metal.h>
#include <torch/torch.h>

// PyTorch MPS stream integration (not in TORCH_STABLE_ONLY builds).
#if !defined(TORCH_STABLE_ONLY) && !defined(TORCH_TARGET_VERSION)
  #include <ATen/mps/MPSStream.h>
  #define BRUTE_MPS_STREAM 1
#endif

