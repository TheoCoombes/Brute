// brute Metal/MPS backend — driver layer.
//
// All bit1 packed buffers are int64 (uint64 view, 64 bits per word). Kernels
// live in cbrute/metal/kernels/*.metal, compiled AOT by CMake into a single
// .metallib whose bytes are embedded into the extension via the generated
// brute_kernels_data.h. We load it at startup with [device newLibraryWithData:].
//
// Stream integration: when PyTorch's MPS stream is available we encode into
// its current command buffer. Before opening any compute encoder we MUST call
// `stream->endKernelCoalescing()` — otherwise a prior at:: op may still hold
// an encoder open on the same command buffer, triggering Metal's "A command
// encoder is already encoding to this command buffer" abort.

