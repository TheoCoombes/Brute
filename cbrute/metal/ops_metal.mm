constexpr int64_t PACK_WIDTH = 64;

//  Pipeline cache: two-tier.
//   * shared_mutex-guarded unordered_map handles arbitrary kernel names.
//   * Each call site holds a per-callsite atomic slot; hot dispatches bypass
//     the map after the first compile.
struct PipelineCache {
    std::shared_mutex mtx;
    id<MTLDevice>       dev       = nil;
    id<MTLLibrary>      lib       = nil;
    id<MTLCommandQueue> own_queue = nil;   // used when no MPS stream available
    std::unordered_map<std::string, id<MTLComputePipelineState>> states;

    void ensure_lib() {
        if (lib) return;
        dev = MTLCreateSystemDefaultDevice();
        TORCH_CHECK(dev, "Metal: no default device");
        own_queue = [dev newCommandQueue];
        dispatch_data_t data = dispatch_data_create(
            kBruteKernelsMetallib, kBruteKernelsMetallib_len,
            nullptr, DISPATCH_DATA_DESTRUCTOR_DEFAULT);
        NSError* err = nil;
        lib = [dev newLibraryWithData:data error:&err];
        TORCH_CHECK(lib, "Metal library load failed: ",
                    err ? [[err localizedDescription] UTF8String] : "unknown");
    }

    id<MTLComputePipelineState> get(const std::string& name) {
        {
            std::shared_lock<std::shared_mutex> rlock(mtx);
            auto it = states.find(name);
            if (it != states.end()) return it->second;
        }
        std::unique_lock<std::shared_mutex> wlock(mtx);
        auto it = states.find(name);
        if (it != states.end()) return it->second;
        ensure_lib();
        NSError* err = nil;
        id<MTLFunction> fn = [lib newFunctionWithName:
                              [NSString stringWithUTF8String:name.c_str()]];
        TORCH_CHECK(fn, "Metal kernel not found: ", name);
        id<MTLComputePipelineState> ps =
            [dev newComputePipelineStateWithFunction:fn error:&err];
        TORCH_CHECK(ps, "Metal pipeline error for ", name, ": ",
                    err ? [[err localizedDescription] UTF8String] : "unknown");
        states[name] = ps;
        return ps;
    }

    id<MTLCommandBuffer> cmd_buf() {
#if BRUTE_MPS_STREAM
        // Flush any pending at:: encoder on PyTorch's command buffer BEFORE
        // we open ours.
        auto stream = at::mps::getCurrentMPSStream();
        stream->endKernelCoalescing();
        return (id<MTLCommandBuffer>)stream->commandBuffer();
#else
        std::lock_guard<std::shared_mutex> lock(mtx);
        ensure_lib();
        return [own_queue commandBuffer];
#endif
    }

    void commit_if_standalone(id<MTLCommandBuffer> buf) {
#if !BRUTE_MPS_STREAM
        [buf commit];
        [buf waitUntilCompleted];
#endif
    }
};

static PipelineCache g_cache;

// Per-callsite cache: store the resolved pipeline state in a static atomic so
// subsequent dispatches at the same call site bypass the shared-mutex lookup
// entirely. Pipeline states are owned by g_cache for the program lifetime —
// safe to publish a raw pointer.
static inline id<MTLComputePipelineState> cached_pipeline(
        std::atomic<void*>& slot, const std::string& name) {
    void* p = slot.load(std::memory_order_acquire);
    if (p != nullptr) return (__bridge id<MTLComputePipelineState>)p;
    id<MTLComputePipelineState> ps = g_cache.get(name);
    slot.store((__bridge void*)ps, std::memory_order_release);
    return ps;
}
#define BRUTE_CACHED_PS(name) ([](){                                         \
        static std::atomic<void*> _ps_slot{nullptr};                         \
        return cached_pipeline(_ps_slot, (name));                            \
    }())

inline id<MTLBuffer> mtl_buf(const at::Tensor& t) {
    return (__bridge id<MTLBuffer>)(t.storage().data());
}
inline NSUInteger byte_offset(const at::Tensor& t) {
    return (NSUInteger)(t.storage_offset() * t.element_size());
}

// Map a torch tensor's scalar type → kernel suffix for the per-element
// `popcount` op (which legitimately supports any integer dtype).
inline const char* type_suffix(const at::Tensor& t) {
    switch (t.scalar_type()) {
        case at::kByte: case at::kBool: return "_u8";
        case at::kInt:                  return "_u32";
        default:                        return "_u64";
    }
}

//  Unified dispatcher
static void dispatch_kernel_ps(
        id<MTLComputePipelineState> ps,
        const std::vector<std::pair<id<MTLBuffer>, NSUInteger>>& bufs,
        const std::vector<int32_t>& consts,
        MTLSize grid, MTLSize tg)
{
    auto cmd = g_cache.cmd_buf();
    id<MTLComputeCommandEncoder> enc =
        [cmd computeCommandEncoderWithDispatchType:MTLDispatchTypeConcurrent];
    [enc setComputePipelineState:ps];
    NSUInteger idx = 0;
    for (const auto& bp : bufs) [enc setBuffer:bp.first offset:bp.second atIndex:idx++];
    for (int32_t v : consts)    [enc setBytes:&v length:sizeof(v)   atIndex:idx++];
    [enc dispatchThreads:grid threadsPerThreadgroup:tg];
    [enc endEncoding];
    g_cache.commit_if_standalone(cmd);
}

static void dispatch_kernel(
        const std::string& name,
        const std::vector<std::pair<id<MTLBuffer>, NSUInteger>>& bufs,
        const std::vector<int32_t>& consts,
        MTLSize grid, MTLSize tg)
{
    dispatch_kernel_ps(g_cache.get(name), bufs, consts, grid, tg);
}

